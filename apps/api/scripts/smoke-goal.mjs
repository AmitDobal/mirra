#!/usr/bin/env node
/**
 * Smoke: goal timeline API (AMI-179). Needs `wrangler dev` with local migrations applied.
 *   API_BASE=http://127.0.0.1:8809 node scripts/smoke-goal.mjs
 * Onboards 82 → 75 kg steady, backdates the plan start 35 days in local D1, logs a weigh-in per
 * simulated day, completes a workout, and prints a short `GET /v1/goal` excerpt before / after.
 */
import { execFileSync } from "node:child_process";

const BASE = (process.env.API_BASE ?? "http://127.0.0.1:8787").replace(/\/$/, "");
const USER = `smoke-goal-${Date.now().toString(36)}`;
const DAY = 86_400_000;
const KG = [
  81.7, 81.3, 81.2, 81.4, 81.2, 81.3, 80.9, 81.2, 80.8, 80.6, 80.9, 80.7, 80.8, 80.4, 80.7, 80.3, 80.1, 80.3,
  80.2, 80.2, 79.9, 80.1, 79.8, 79.6, 79.8, 79.6, 79.7, 79.4, 79.6, 79.3, 79.1, 79.3, 79.1, 79.2, 78.8, 79.1,
];
let failures = 0;
const check = (ok, label, detail = "") => {
  console.log(`${ok ? "PASS" : "FAIL"}  ${label}${detail ? `  - ${detail}` : ""}`);
  if (!ok) failures += 1;
};
const call = async (method, path, body, headers = {}) => {
  const t0 = performance.now();
  const res = await fetch(`${BASE}${path}`, {
    method,
    headers: { "content-type": "application/json", "x-mirra-user-id": USER, ...headers },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const ms = performance.now() - t0;
  return { status: res.status, etag: res.headers.get("etag"), ms, json: res.status === 304 ? null : await res.json().catch(() => null) };
};
const sql = (command) =>
  execFileSync("npx", ["wrangler", "d1", "execute", "mirra-db", "--local", "--command", command], { stdio: "pipe" });
const excerpt = (b) => ({
  plan: b.plan && { version: b.plan.version, startDate: b.plan.startDate, startWeightKg: b.plan.startWeightKg, targetWeightKg: b.plan.targetWeightKg, originalEta: b.plan.originalEta, committedAt: b.plan.committedAt },
  status: b.status,
  band: b.band,
  trendKg: b.trendKg,
  toGoKg: b.toGoKg,
  adherence: b.adherence,
  milestones: b.milestones.map((m) => `${m.id}:${m.date ?? "-"}${m.done ? "✓" : ""}`),
  chartActual: b.chart?.actual.length ?? 0,
});

const onb = await call("PUT", "/v1/onboarding", {
  profile: { sex: "male", ageYears: 29, heightCm: 180, weightKg: 82, goalWeightKg: 75, pace: "steady", timezone: "UTC" },
  preferences: { primaryGoal: "lose_fat", experience: "months", equipment: ["full_gym"], trainDays: [1, 2, 4, 5], sessionMinutes: 45, cuisineStyles: ["american"] },
  commitment: { committedAt: Date.now() },
});
check(onb.status === 200, "PUT /v1/onboarding", String(onb.status));
const g0 = await call("GET", "/v1/goal");
check(g0.status === 200 && g0.json?.plan?.version === 1 && !!g0.etag, "GET /v1/goal day 0", g0.etag ?? "");
console.log("day 0:", JSON.stringify(excerpt(g0.json)));
const g0b = await call("GET", "/v1/goal", undefined, { "if-none-match": g0.etag });
check(g0b.status === 304, "If-None-Match → 304", String(g0b.status));

// Simulate 35 days: backdate the frozen plan start, then one weigh-in per day.
const today = new Date().toISOString().slice(0, 10);
const start = new Date(Date.parse(`${today}T12:00:00Z`) - 35 * DAY);
sql(`UPDATE goal_plans SET start_date = '${start.toISOString().slice(0, 10)}' WHERE user_id = '${USER}'`);
const lat = [];
for (const [d, kg] of KG.entries()) {
  const w = await call("POST", "/v1/weight", { kg, loggedAt: start.getTime() + d * DAY });
  if (w.status !== 201) check(false, `POST /v1/weight day ${d}`, String(w.status));
  lat.push(w.ms);
}
lat.sort((a, b) => a - b);
check(true, "36 weigh-ins logged", `p50 ${lat[18].toFixed(1)} ms incl. goal refresh`);

// Complete one workout (plan generated by the heuristic adapter).
const job = await call("POST", "/v1/plans/generate", {});
for (let i = 0; i < 30; i += 1) {
  const j = (await call("GET", `/v1/plans/jobs/${job.json?.jobId}`)).json;
  if (j?.status === "succeeded" || j?.status === "ready" || j?.planId) break;
  await new Promise((r) => setTimeout(r, 500));
}
const plan = (await call("GET", "/v1/plans/current")).json;
const workoutId = plan?.workouts?.[0]?.id;
const ses = await call("POST", "/v1/workouts/sessions", { workoutId });
const done = await call("POST", `/v1/workouts/sessions/${ses.json?.id}/complete`, { rpe: 7 });
check(done.status === 200, "workout complete", `${done.status} in ${done.ms.toFixed(0)} ms`);

const g1 = await call("GET", "/v1/goal", undefined, { "if-none-match": g0.etag });
check(g1.status === 200 && g1.etag !== g0.etag, "old ETag after activity → 200 + new ETag", `${g0.etag} → ${g1.etag}`);
check(g1.json?.plan?.startWeightKg === 82 && g1.json?.chart?.actual.length === 36, "start frozen at 82 kg, 36 actual points");
console.log("day 35:", JSON.stringify(excerpt(g1.json)));
const g2 = await call("GET", "/v1/goal", undefined, { "if-none-match": g1.etag });
check(g2.status === 304, "new ETag → 304", `${g2.status} in ${g2.ms.toFixed(1)} ms`);
const rs = await call("POST", "/v1/goal/restart");
const rs2 = await call("POST", "/v1/goal/restart");
check(rs.status === 201 && rs2.status === 429, "restart 201, then 429", `${rs.status} ${rs2.status} v${rs.json?.plan?.version}`);

console.log(failures ? `\n${failures} failed` : "\nPASS smoke goal");
process.exit(failures ? 1 : 0);
